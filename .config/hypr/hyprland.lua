---- Layouts ---------------------------------------------------------------

-- Cycle layout
hl.bind(mainMod .. " + SHIFT + SPACE", function()
    currentLayout = currentLayout % #layouts + 1
    hl.config({ general = { layout = layouts[currentLayout] } })
    hl.dispatch(hl.dsp.exec_cmd("notify-send 'Layout' '" .. layouts[currentLayout] .. "'"))
end)

-- Toggle column width (scrolling)
local colFull = false

hl.bind(mainMod .. " + SHIFT + F", function()
    colFull = not colFull
    if colFull then
        hl.dispatch(hl.dsp.layout("fit active"))
    else
        hl.dispatch(hl.dsp.layout("colresize 0.5"))
        hl.dispatch(hl.dsp.focus({ direction = "left" }))
        hl.dispatch(hl.dsp.focus({ direction = "right" }))
    end
end)

-- Toggle split / orientation
hl.bind(mainMod .. " + V", function()
    local layout = layouts[currentLayout]
    if layout == "dwindle" then
        hl.dispatch(hl.dsp.layout("togglesplit"))
    elseif layout == "master" then
        hl.dispatch(hl.dsp.layout("orientationcycle"))
    end
end)


